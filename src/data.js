// Код цвета вида "S05" / "P12" — используется в карте цветов и спецификации.
export const codeOf = (fabricId, n) =>
  (fabricId === 'sil' ? 'S' : 'P') + String(n).padStart(2, '0');

const COLOR_INDEX = new Map();
for (const f of FABRIC_ORDER) {
  for (const c of FABRICS[f].colors) {
    COLOR_INDEX.set(codeOf(f, c.n), {
      ...c, fabric: f, code: codeOf(f, c.n), fabricLabel: FABRICS[f].label,
    });
  }
}
export const colorByCode = (code) => COLOR_INDEX.get(code) || null;
export const hexOf = (code) => (COLOR_INDEX.get(code) || { hex: '#D8D8D8' }).hex;
export const ALL_COLORS = [...COLOR_INDEX.values()];

